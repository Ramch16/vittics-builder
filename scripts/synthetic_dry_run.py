"""Deterministic synthetic dry run of the benchmark record pipeline. No model, no agents, no network.

    python scripts/synthetic_dry_run.py --out evidence/week1/<capture-id>/synthetic-dry-run

Writes records.jsonl (12 invented runs: 3 tasks x 2 conditions x 2 repeats, every one data_kind "synthetic"),
validation.json (schema errors per record; all empty when valid) and summary.json
(benchmarks.summarize_records). The runs are designed to exercise:
  - an unknown cost (an incomplete run with ended_at null) that must make the condition's total cost unknown;
  - failed, timed-out and provider-unavailable outcomes that still count;
  - a condition with zero accepted runs, whose cost per accepted run must be undefined (null).
The numbers are invented. They are not results and must never be copied into an actual-results folder.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from vittics_builder.benchmarks import SCHEMA_PATH, summarize_records, validate_record

ROOT = Path(__file__).resolve().parent.parent
HARNESS = "0" * 40                                      # placeholder commit: synthetic records name no real run


def h(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def record(task: str, condition: str, repeat: int, status: str, *, cost: float | None = 0.5,
           ended: str | None = "2026-01-01T00:20:00Z", release: str = "released", oracle: bool | None = True) -> dict:
    run = f"{task}-{condition}-{repeat}"
    return {
        "schema_version": 1, "data_kind": "synthetic", "experiment_id": "dry-run-0", "run_id": run,
        "task_id": task, "condition": condition, "repeat": repeat,
        "source": {"harness_commit": HARNESS, "starter_tree_sha256": h(f"starter-{task}")},
        "hashes": {k: h(f"{k}-{task}") for k in ("task", "prompt", "oracle", "config")},
        "engine": {"provider": "synthetic", "model": "none", "model_version": None, "engine": "mock",
                   "engine_version": None},
        "environment_ref": "synthetic", "started_at": "2026-01-01T00:00:00Z", "ended_at": ended,
        "terminal_status": status, "blocker": None if status in ("accepted", "rejected") else f"synthetic {status}",
        "acceptance": {"checks": [{"id": "oracle", "passed": oracle}], "all_passed": oracle, "release_outcome": release},
        "retries": {"builder_rework": 1 if status == "rejected" else 0, "reviewer_retry": 0,
                    "infrastructure_retry": 1 if status == "provider_unavailable" else 0},
        "human_interventions": [{"kind": "approval", "role": "cto", "at": "2026-01-01T00:10:00Z", "minutes": 2}],
        "usage": {"input_tokens": None if cost is None else 1000, "output_tokens": None if cost is None else 200,
                  "cache_read_tokens": None, "cache_write_tokens": None},
        "cost": {"amount": cost, "currency": "USD" if cost is not None else None,
                 "basis": "estimated" if cost is not None else "unknown",
                 "price_source": "synthetic" if cost is not None else None,
                 "price_source_date": "2026-01-01" if cost is not None else None},
        "timing": {"wall_seconds": 1200 if ended else None, "active_union_seconds": 900 if ended else None,
                   "summed_agent_seconds": 1100 if ended else None,
                   "waits": {"human": 120 if ended else None, "provider_unavailable": 0, "infrastructure": 0,
                             "unclassified": None}},
        "artifacts": [{"path": f"synthetic/{run}.log", "sha256": h(run)}],
        "ai_assistance": "Generated by scripts/synthetic_dry_run.py (written with Claude Code); no AI run occurred.",
        "limitations": ["Invented data for pipeline validation only."],
    }


def synthetic_records() -> list[dict]:
    m, s = "multi_agent", "single_agent"
    return [
        record("T1", m, 1, "accepted"), record("T1", m, 2, "accepted"),
        record("T1", s, 1, "rejected", release="release_blocked", oracle=False),
        record("T1", s, 2, "rejected", release="release_blocked", oracle=False),
        record("T2", m, 1, "accepted"), record("T2", m, 2, "failed", release="not_reached", oracle=False),
        record("T2", s, 1, "failed", release="not_reached", oracle=False),
        record("T2", s, 2, "timeout", release="not_reached", oracle=None),
        record("T3", m, 1, "accepted"),
        record("T3", m, 2, "incomplete", cost=None, ended=None, release="unknown", oracle=None),
        record("T3", s, 1, "provider_unavailable", release="not_reached", oracle=None),
        record("T3", s, 2, "rejected", release="not_reached", oracle=False),
    ]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    schema = json.loads((ROOT / SCHEMA_PATH).read_text(encoding="utf-8"))
    records = synthetic_records()
    errors = {r["run_id"]: validate_record(r, schema) for r in records}
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "records.jsonl").write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in records), encoding="utf-8")
    (out / "validation.json").write_text(json.dumps(errors, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (out / "summary.json").write_text(json.dumps(summarize_records(records), indent=2, sort_keys=True) + "\n",
                                      encoding="utf-8")
    print(out)
    return 0 if not any(errors.values()) else 1


if __name__ == "__main__":
    raise SystemExit(main())
